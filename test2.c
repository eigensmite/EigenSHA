/* ------------------------------------------------------------------------ */
/* 6. Streaming / incremental update consistency                             */
/* ------------------------------------------------------------------------ */

#define STREAM_LEN 1000

static void test_streaming(void) {
  uint8_t msg[STREAM_LEN];
  uint32_t x = 0x12345678u; /* deterministic xorshift */
  for (size_t i = 0; i < STREAM_LEN; i++) {
    x ^= x << 13;
    x ^= x >> 17;
    x ^= x << 5;
    msg[i] = (uint8_t)x;
  }

  for (int s = 0; s < SHA_COUNT; s++) {
    enum Sha sha = (enum Sha)s;
    uint8_t ref[MAX_DIGEST], md[MAX_DIGEST];
    char exp[2 * MAX_DIGEST + 1], got[2 * MAX_DIGEST + 1];
    size_t n = hash_once(sha, ref, msg, STREAM_LEN);
    tohex(exp, ref, n);

    /* Two updates, split at every offset 0..STREAM_LEN */
    size_t bad_split = (size_t)-1;
    for (size_t cut = 0; cut <= STREAM_LEN; cut++) {
      eigensha_ctx c;
      eigensha_init(&c, sha);
      eigensha_update(&c, msg, cut);
      eigensha_update(&c, msg + cut, STREAM_LEN - cut);
      eigensha_finalize(&c);
      eigensha_extract(md, &c);
      eigensha_free(&c);
      if (memcmp(md, ref, n) != 0) {
        bad_split = cut;
        tohex(got, md, n);
        break;
      }
    }
    char what[96];
    if (bad_split == (size_t)-1)
      record(sha, 1, "streaming: 2 updates split at every offset 0..1000", NULL,
             NULL);
    else {
      snprintf(what, sizeof what, "streaming: 2 updates split at offset %zu",
               bad_split);
      record(sha, 0, what, exp, got);
    }

    /* Byte-at-a-time, with zero-length updates interleaved */
    {
      eigensha_ctx c;
      eigensha_init(&c, sha);
      for (size_t i = 0; i < STREAM_LEN; i++) {
        eigensha_update(&c, msg + i, 1);
        eigensha_update(&c, msg, 0);
      }
      eigensha_finalize(&c);
      eigensha_extract(md, &c);
      eigensha_free(&c);
      tohex(got, md, n);
      record(sha, !memcmp(md, ref, n),
             "streaming: byte-at-a-time + zero-length updates", exp, got);
    }

    /* Odd-sized chunks (7, 61, 127, 143 bytes) */
    static const size_t chunks[] = {7, 61, 127, 143};
    for (size_t k = 0; k < COUNT(chunks); k++) {
      eigensha_ctx c;
      eigensha_init(&c, sha);
      for (size_t off = 0; off < STREAM_LEN; off += chunks[k]) {
        size_t take =
            STREAM_LEN - off < chunks[k] ? STREAM_LEN - off : chunks[k];
        eigensha_update(&c, msg + off, take);
      }
      eigensha_finalize(&c);
      eigensha_extract(md, &c);
      eigensha_free(&c);
      tohex(got, md, n);
      snprintf(what, sizeof what, "streaming: %zu-byte chunks", chunks[k]);
      record(sha, !memcmp(md, ref, n), what, exp, got);
    }
  }
}

