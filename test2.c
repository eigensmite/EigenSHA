static unsigned long g_pass[SHA_COUNT], g_fail[SHA_COUNT];
static int g_verbose = 0;

static void record(enum Sha sha, int ok, const char *what, const char *exp,
                   const char *got) {
  if (ok) {
    g_pass[sha]++;
    if (g_verbose)
      printf("  [PASS] %-12s %s\n", ALGO[sha].label, what);
  } else {
    g_fail[sha]++;
    printf("  [FAIL] %-12s %s\n", ALGO[sha].label, what);
    if (exp)
      printf("         exp: %s\n", exp);
    if (got)
      printf("         got: %s\n", got);
  }
}

