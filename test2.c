int main(int argc, char **argv) {
  const char *cavp_dir = NULL;
  for (int i = 1; i < argc; i++) {
    if (!strcmp(argv[i], "-v"))
      g_verbose = 1;
    else if (!strcmp(argv[i], "-h") || !strcmp(argv[i], "--help")) {
      printf("usage: %s [-v] [cavp_rsp_dir]\n", argv[0]);
      return 0;
    } else
      cavp_dir = argv[i];
  }

  printf("EigenSHA test battery\n");
  printf("=====================\n\n");

  printf("[1/7] digest lengths\n");
  test_lengths();
  printf("[2/7] NIST example messages\n");
  test_examples();
  printf("[3/7] CAVP ShortMsg/LongMsg (embedded, %zu vectors)\n", COUNT(KAT));
  test_kat();
  printf("[4/7] CAVP Monte Carlo (embedded)\n");
  test_monte();
  printf("[5/7] streaming consistency\n");
  test_streaming();
  printf("[6/7] context reuse\n");
  test_reuse();

  if (cavp_dir) {
    printf("[7/7] full CAVP vector files from %s\n", cavp_dir);
    for (int s = 0; s < SHA_COUNT; s++) {
      cavp_msg_file((enum Sha)s, cavp_dir, "ShortMsg");
      cavp_msg_file((enum Sha)s, cavp_dir, "LongMsg");
      cavp_monte_file((enum Sha)s, cavp_dir);
    }
  } else {
    printf("[7/7] full CAVP vector files: skipped (pass a directory of .rsp "
           "files to run)\n");
  }

  unsigned long tp = 0, tf = 0;
  printf("\nSummary\n-------\n");
  printf("  %-12s %8s %8s  %s\n", "Algorithm", "passed", "failed", "result");
  for (int s = 0; s < SHA_COUNT; s++) {
    printf("  %-12s %8lu %8lu  %s\n", ALGO[s].label, g_pass[s], g_fail[s],
           g_fail[s] ? "FAIL" : "PASS");
    tp += g_pass[s];
    tf += g_fail[s];
  }
  printf("  %-12s %8lu %8lu  %s\n\n", "TOTAL", tp, tf, tf ? "FAIL" : "PASS");

  if (tf)
    printf("%lu check(s) FAILED.\n", tf);
  else
    printf("All %lu checks passed.\n", tp);
  printf("\nThis test file was generated by Claude Opus 5.5\n");
  return tf ? 1 : 0;
}
