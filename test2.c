static int hexval(char c) {
  if (c >= '0' && c <= '9')
    return c - '0';
  if (c >= 'a' && c <= 'f')
    return c - 'a' + 10;
  if (c >= 'A' && c <= 'F')
    return c - 'A' + 10;
  return -1;
}

/* Decode n bytes of hex into out. */
static void unhex(uint8_t *out, const char *hex, size_t n) {
  for (size_t i = 0; i < n; i++)
    out[i] = (uint8_t)((hexval(hex[2 * i]) << 4) | hexval(hex[2 * i + 1]));
}

static void tohex(char *out, const uint8_t *in, size_t n) {
  static const char d[] = "0123456789abcdef";
  for (size_t i = 0; i < n; i++) {
    out[2 * i] = d[in[i] >> 4];
    out[2 * i + 1] = d[in[i] & 15];
  }
  out[2 * n] = '\0';
}

/* One-shot hash; returns digest length reported by the library. */
static size_t hash_once(enum Sha sha, uint8_t *out, const uint8_t *msg,
                        size_t len) {
  eigensha_ctx c;
  eigensha_init(&c, sha);
  eigensha_update(&c, (void *)msg, len);
  eigensha_finalize(&c);
  eigensha_extract(out, &c);
  size_t n = eigensha_get_hash_len(&c);
  eigensha_free(&c);
  return n;
}

/* Hash and compare against expected hex; compares the FULL digest. */
static void check_hash(enum Sha sha, const char *what, const uint8_t *msg,
                       size_t len, const char *exp_hex) {
  uint8_t md[MAX_DIGEST];
  char got[2 * MAX_DIGEST + 1];
  size_t n = hash_once(sha, md, msg, len);
  tohex(got, md, n);
  int ok = strlen(exp_hex) == 2 * n && strcmp(got, exp_hex) == 0;
  record(sha, ok, what, exp_hex, got);
}

/* NIST SHAVS Monte Carlo. Writes the 100 checkpoint digests into cp. */
static void monte_carlo(enum Sha sha, const uint8_t *seed_in, size_t L,
                        uint8_t cp[100][MAX_DIGEST]) {
  uint8_t seed[MAX_DIGEST], md[3][MAX_DIGEST], buf[3 * MAX_DIGEST];
  memcpy(seed, seed_in, L);

  for (int j = 0; j < 100; j++) {
    if (ALGO[sha].sha3) {
      /* FIPS 202 SHAVS: MD_i = SHA3(MD_{i-1}) */
      for (int i = 0; i < 1000; i++) {
        memcpy(buf, seed, L);
        hash_once(sha, seed, buf, L);
      }
    } else {
      /* FIPS 180-4 SHAVS: M_i = MD_{i-3} || MD_{i-2} || MD_{i-1} */
      for (int k = 0; k < 3; k++)
        memcpy(md[k], seed, L);
      for (int i = 3; i < 1003; i++) {
        memcpy(buf, md[0], L);
        memcpy(buf + L, md[1], L);
        memcpy(buf + 2 * L, md[2], L);
        memcpy(md[0], md[1], L);
        memcpy(md[1], md[2], L);
        hash_once(sha, md[2], buf, 3 * L);
      }
      memcpy(seed, md[2], L);
    }
    memcpy(cp[j], seed, L);
  }
}

