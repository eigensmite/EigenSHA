/* 7. Context reuse                                                          */
/* ------------------------------------------------------------------------ */

static void test_reuse(void) {
  eigensha_ctx c; /* one context reused across every algorithm */
  uint8_t abc[3] = {'a', 'b', 'c'};
  for (int s = 0; s < SHA_COUNT; s++) {
    uint8_t a[MAX_DIGEST], b[MAX_DIGEST];
    char ha[2 * MAX_DIGEST + 1], hb[2 * MAX_DIGEST + 1];
    for (int r = 0; r < 2; r++) {
      eigensha_init(&c, (enum Sha)s);
      eigensha_update(&c, abc, 3);
      eigensha_finalize(&c);
      eigensha_extract(r ? b : a, &c);
      eigensha_free(&c);
    }
    size_t n = ALGO[s].digest;
    tohex(ha, a, n);
    tohex(hb, b, n);
    record((enum Sha)s, !memcmp(a, b, n),
           "context reuse: init/free x2 identical", ha, hb);
  }
}

/* ------------------------------------------------------------------------ */
/* Full CAVP mode: parse NIST .rsp files from a directory                    */
/* ------------------------------------------------------------------------ */

static char *read_file(const char *path) {
  FILE *f = fopen(path, "rb");
  if (!f)
    return NULL;
  fseek(f, 0, SEEK_END);
  long sz = ftell(f);
  fseek(f, 0, SEEK_SET);
  char *s = malloc((size_t)sz + 1);
  if (!s) {
    fclose(f);
    return NULL;
  }
  size_t got = fread(s, 1, (size_t)sz, f);
  s[got] = '\0';
  fclose(f);
  return s;
}

/* Find "key = value" at or after *p; returns pointer to value, advances *p. */
static const char *next_field(const char **p, const char *key, size_t *vlen) {
  size_t kl = strlen(key);
  for (const char *q = *p; (q = strstr(q, key)) != NULL; q += kl) {
    if (q != *p && q[-1] != '\n')
      continue; /* line start only */
    const char *v = q + kl;
    while (*v == ' ')
      v++;
    if (*v != '=')
      continue;
    v++;
    while (*v == ' ')
      v++;
    size_t n = 0;
    while (hexval(v[n]) >= 0)
      n++;
    *vlen = n;
    *p = v + n;
    return v;
  }
  return NULL;
}

static void cavp_msg_file(enum Sha sha, const char *dir, const char *kind) {
  char path[1024];
  snprintf(path, sizeof path, "%s/%s%s.rsp", dir, ALGO[sha].rsp, kind);
  char *txt = read_file(path);
  if (!txt) {
    printf("  [SKIP] %-12s %s%s.rsp not found\n", ALGO[sha].label,
           ALGO[sha].rsp, kind);
    return;
  }

  unsigned long pass = 0, fail = 0;
  const char *p = txt, *v;
  size_t vl;
  while ((v = next_field(&p, "Len", &vl)) != NULL) {
    size_t bits = strtoul(v, NULL, 10), len = bits / 8;
    const char *msg = next_field(&p, "Msg", &vl);
    const char *md = next_field(&p, "MD", &vl);
    if (!msg || !md)
      break;

    uint8_t *buf = malloc(len ? len : 1);
    unhex(buf, msg, len);
    uint8_t out[MAX_DIGEST];
    char got[2 * MAX_DIGEST + 1], exp[2 * MAX_DIGEST + 1];
    size_t n = hash_once(sha, out, buf, len);
    free(buf);
    tohex(got, out, n);
    size_t el = vl < 2 * MAX_DIGEST ? vl : 2 * MAX_DIGEST;
    memcpy(exp, md, el);
    exp[el] = '\0';
    for (size_t i = 0; i < el; i++)
      if (exp[i] >= 'A' && exp[i] <= 'F')
        exp[i] += 32;

    char what[64];
    snprintf(what, sizeof what, "CAVP %s Len=%zu", kind, bits);
    int ok = el == 2 * n && !strcmp(got, exp);
    if (ok)
      pass++;
    else
      fail++;
    record(sha, ok, what, exp, got);
  }
  printf("  %-12s %-8s %5lu/%-5lu %s\n", ALGO[sha].label, kind, pass,
         pass + fail, (fail || !pass) ? "FAIL" : "pass");
  if (!pass && !fail)
    record(sha, 0, "CAVP file contained no vectors", NULL, NULL);
  free(txt);
}

static void cavp_monte_file(enum Sha sha, const char *dir) {
  char path[1024];
  snprintf(path, sizeof path, "%s/%sMonte.rsp", dir, ALGO[sha].rsp);
  char *txt = read_file(path);
  if (!txt) {
    printf("  [SKIP] %-12s %sMonte.rsp not found\n", ALGO[sha].label,
           ALGO[sha].rsp);
    return;
  }

  const char *p = txt, *v;
  size_t vl;
  v = next_field(&p, "Seed", &vl);
  if (!v) {
    record(sha, 0, "CAVP Monte: no Seed", NULL, NULL);
    free(txt);
    return;
  }
  size_t L = vl / 2;
  uint8_t seed[MAX_DIGEST];
  unhex(seed, v, L);

  static uint8_t cp[100][MAX_DIGEST];
  monte_carlo(sha, seed, L, cp);

  unsigned long pass = 0, fail = 0;
  for (int j = 0; j < 100 && (v = next_field(&p, "MD", &vl)) != NULL; j++) {
    char got[2 * MAX_DIGEST + 1], exp[2 * MAX_DIGEST + 1], what[64];
    tohex(got, cp[j], L);
    size_t el = vl < 2 * MAX_DIGEST ? vl : 2 * MAX_DIGEST;
    memcpy(exp, v, el);
    exp[el] = '\0';
    snprintf(what, sizeof what, "CAVP Monte COUNT=%d", j);
    int ok = !strcmp(got, exp);
    if (ok)
      pass++;
    else
      fail++;
    record(sha, ok, what, exp, got);
  }
  printf("  %-12s %-8s %5lu/%-5lu %s\n", ALGO[sha].label, "Monte", pass,
         pass + fail, (fail || pass != 100) ? "FAIL" : "pass");
  free(txt);
}

